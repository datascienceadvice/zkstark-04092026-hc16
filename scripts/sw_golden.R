run <- function(x, label) {
  r <- tryCatch(shapiro.test(x), error = function(e) NULL)
  if (is.null(r)) {
    cat(label, "ERROR", "\n")
  } else {
    cat(label, sprintf("W=%.17g p=%.17g", r$statistic, r$p.value), "\n")
  }
}
